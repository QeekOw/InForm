"""Check a sharded dataset before anyone trains on it.

A retrain is a comparison between two datasets, so a set whose shards disagree,
or whose fingerprint does not match the commit being trained, produces a result
nobody can attribute. That has already happened once: the 270 fat-figure fix
moved 23% of 570 sheets as an unrecorded side effect (ADR-0007, 2026-09-11).

Checks, in the order they are worth failing on:

1. every shard's `generator_fingerprint` agrees with the others;
2. that fingerprint matches the working tree, so the set matches the commit;
3. the shards' seed ranges tile without gaps or overlaps, per device;
4. every sheet has its label JSON and every label its sheet;
5. the sheet count matches what the manifests promise.

    python scripts/verify_dataset.py D:/cera/data/synth_v6_both [--expect 5000]
"""

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from inform.training.dataset import generator_fingerprint  # noqa: E402

_SUFFIXES = {".jpg", ".jpeg", ".png"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("data_dir", type=Path)
    parser.add_argument("--expect", type=int, default=None, help="Expected sheet count")
    args = parser.parse_args()

    manifests = sorted(args.data_dir.glob("dataset.*.json"))
    if not manifests:
        print(f"FAIL  no dataset.*.json manifests in {args.data_dir}")
        return 1

    failures = []
    loaded = [(p, json.loads(p.read_text(encoding="utf-8"))) for p in manifests]
    print(f"{len(loaded)} shard manifests in {args.data_dir}\n")

    # 1 + 2. Fingerprints agree with each other and with the working tree.
    expected = generator_fingerprint()
    seen = {m["generator_fingerprint"] for _, m in loaded}
    print(f"  working tree  {expected[:16]}")
    if len(seen) != 1:
        failures.append(f"shards disagree on generator_fingerprint: {len(seen)} distinct values")
        for fingerprint in sorted(seen):
            print(f"  shards        {fingerprint[:16]}  one of {len(seen)} -- DISAGREE")
    else:
        actual = seen.pop()
        match = actual == expected
        print(f"  shards        {actual[:16]}  {'OK' if match else 'MISMATCH'}")
        if not match:
            failures.append(
                "the set was generated by different code than the working tree; train the "
                "commit that made it, or regenerate"
            )

    # 3. Seed ranges tile per device.
    by_device = defaultdict(list)
    promised = 0
    for path, manifest in loaded:
        promised += manifest["sheets"]
        for device in manifest["devices"]:
            by_device[device].append((manifest["seed_start"], manifest["seed_end"], path.name))
    for device, spans in sorted(by_device.items()):
        spans.sort()
        gaps = [
            f"{spans[i][1]}->{spans[i + 1][0]}"
            for i in range(len(spans) - 1)
            if spans[i + 1][0] != spans[i][1] + 1
        ]
        total = sum(end - start + 1 for start, end, _ in spans)
        note = "OK" if not gaps else "GAP/OVERLAP at " + ", ".join(gaps)
        if gaps:
            failures.append(f"{device}: {note}")
        print(f"  {device:12s} {len(spans)} shards, seeds {spans[0][0]}-{spans[-1][1]}, {total} sheets  {note}")

    # 4 + 5. Every sheet is paired, and there are as many as promised.
    sheets = {p.stem for p in args.data_dir.iterdir() if p.suffix.lower() in _SUFFIXES}
    labels = {
        p.stem
        for p in args.data_dir.glob("*.json")
        if not p.name.startswith("dataset.")
    }
    orphan_sheets, orphan_labels = sheets - labels, labels - sheets
    if orphan_sheets:
        failures.append(f"{len(orphan_sheets)} sheets with no label JSON")
    if orphan_labels:
        failures.append(f"{len(orphan_labels)} labels with no sheet")
    print(f"\n  {len(sheets)} sheets, {len(labels)} labels, {len(orphan_sheets) + len(orphan_labels)} unpaired")

    target = args.expect if args.expect is not None else promised
    if len(sheets) != target:
        failures.append(f"expected {target} sheets, found {len(sheets)}")
    print(f"  manifests promise {promised}; expected {target}")

    print()
    for failure in failures:
        print(f"FAIL  {failure}")
    if not failures:
        print("All checks passed.")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
